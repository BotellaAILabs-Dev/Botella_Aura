export function websitePlatform(id: string): WebsitePlatform | undefined {
  return WEBSITE_PLATFORMS.find((p) => p.id === id);
}

/** What the person sees for a connection's state. */
export type WebsiteConnectionState = 'connected' | 'error' | 'reauth' | 'not_connected';

export const CONNECTION_STATE_LABEL: Record<WebsiteConnectionState, string> = {
  connected: 'Connected',
  error: 'Connection error',
  reauth: 'Reconnect required',
  not_connected: 'Not connected',
};

export function connectionState(status: 'CONNECTED' | 'ERROR' | 'REAUTH_REQUIRED' | 'DISCONNECTED'): WebsiteConnectionState {
  if (status === 'CONNECTED') return 'connected';
  if (status === 'ERROR') return 'error';
  if (status === 'REAUTH_REQUIRED') return 'reauth';
  return 'not_connected';
}

