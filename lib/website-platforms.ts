/**
 * Website / CMS platforms Aura can publish blogs to — the client-safe half of
 * the integration framework (server/websites holds the adapters).
 *
 * Adding a platform:
 *   1. an entry here (what the person sees, which fields they fill in, what
 *      the platform can hold)
 *   2. an adapter in server/websites/adapters/<id>.ts, registered in
 *      server/websites/registry.ts
 * Nothing else changes: connections, publishing, scheduling, retries and
 * history are platform-agnostic (docs/WEBSITE-PUBLISHING.md).
 */

/**
 * `available`    - an adapter exists and publishes end-to-end.
 * `planned`      - has an official API; listed so the roadmap is visible.
 * `no_api`       - the platform has no API for creating blog posts. Said
 *                  plainly, with the closest option, rather than "coming soon".
 */
export type WebsitePlatformStatus = 'available' | 'planned' | 'no_api';

/** A field the person fills in to connect (never echoed back once saved). */
export interface ConnectField {
  key: string;
  label: string;
  placeholder?: string;
  help?: string;
  secret?: boolean;
  optional?: boolean;
}

/** Every SEO field the requirement names, and how each platform holds it. */
export type SeoField =
  | 'seoTitle'
  | 'metaDescription'
  | 'slug'
  | 'canonicalUrl'
  | 'focusKeyword'
  | 'ogImage'
  | 'imageAlt'
  | 'schema';

/**
 * native    - the platform stores it itself.
 * plugin    - needs a plugin that exposes it (WordPress + Yoast / Rank Math).
 * fallback  - not held as such; Aura writes the closest field (named in `note`).
 * none      - nothing to write it to.
 */
export type SeoSupport = 'native' | 'plugin' | 'fallback' | 'none';

export interface WebsitePlatform {
  id: string;
  name: string;
  status: WebsitePlatformStatus;
  color: string;
  description: string;
  /** How connecting works, in one line. */
  authSummary: string;
  /** "oauth" platforms start with a redirect; the others are a form. */
  connect: 'form' | 'oauth';
  fields: ConnectField[];
  /** Can a post be created unpublished on the site? */
  supportsDraft: boolean;
  /** Categories as such (Shopify has blogs, Ghost has a primary tag). */
  categories: 'native' | 'fallback' | 'none';
  seo: Record<SeoField, { support: SeoSupport; note?: string }>;
  /** Plain-language limits, shown before connecting and in the docs. */
  limitations: string[];
  docsUrl: string;
}

