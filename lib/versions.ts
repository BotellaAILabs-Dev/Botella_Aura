/**
 * Content versions: every state of a piece of generated work, kept.
 *
 * Version 1 is what Aura generated. Every later change — a person's edit, a
 * regeneration, a switch to another variation, an undo, restoring an older
 * version — adds a new numbered version with who made it and when. Nothing is
 * overwritten: restoring version 2 creates version 7 "restored from v2".
 * The original and the approved version are never dropped, whatever the cap.
 *
 * Shared by Content Studio drafts (the body is the draft's JSON) and outreach
 * messages (the body is the text). Pure and client-safe; stored in the item's
 * aiMetadata.versions (server/versions/version.service.ts).
 */

export const VERSION_SOURCES = [
  'generated',
  'edited',
  'regenerated',
  'variation',
  'undo',
  'restored',
] as const;
export type VersionSource = (typeof VERSION_SOURCES)[number];

export const VERSION_SOURCE_LABEL: Record<VersionSource, string> = {
  generated: 'Generated by Aura',
  edited: 'Edited',
  regenerated: 'Regenerated',
  variation: 'Variation chosen',
  undo: 'Undo',
  restored: 'Restored',
};

export interface ContentVersion {
  n: number;
  source: VersionSource;
  /** User id; null when Aura made it. */
  by: string | null;
  at: string;
  body: unknown;
  hash: string;
  /** For a restore or undo: the version it came back to. */
  basedOn?: number | null;
  note?: string | null;
}

export interface VersionLog {
  model: 1;
  /** The version in use now. */
  current: number;
  /** The version last approved, when there is one (never dropped). */
  approved: { n: number; by: string | null; at: string } | null;
  /** Oldest first. */
  versions: ContentVersion[];
}

/** Versions kept per item — the original and the approved one always among them. */
export const MAX_VERSIONS = 50;

function canon(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(canon);
  if (v && typeof v === 'object') {
    return Object.fromEntries(
      Object.keys(v as object)
        .sort()
        .map((k) => [k, canon((v as Record<string, unknown>)[k])]),
    );
  }
  return v;
}

/** A fingerprint of a body, whatever order its keys were stored in. */
export function bodyFingerprint(body: unknown): string {
  const str = JSON.stringify(canon(body ?? null));
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0).toString(16).padStart(8, '0') + str.length.toString(16);
}

export function versionLogOf(meta: unknown): VersionLog | null {
  const v = (meta as { versions?: VersionLog } | null)?.versions;
  return v &&
    typeof v === 'object' &&
    v.model === 1 &&
    Array.isArray(v.versions)
    ? v
    : null;
}

export function newLog(
  body: unknown,
  at: string,
  by: string | null = null,
): VersionLog {
  return {
    model: 1,
    current: 1,
    approved: null,
    versions: [
      { n: 1, source: 'generated', by, at, body, hash: bodyFingerprint(body) },
    ],
  };
}

/**
 * The log for an item made before versions were kept, rebuilt from what it
 * has: the undo history (oldest first) then the body as it is now.
 */
export function legacyLog(
  body: unknown,
  createdAt: string,
  history: { body: unknown; at?: string; before?: string }[],
): VersionLog {
  const earlier = [...history].reverse();
  const bodies = [
    ...earlier.map((h) => ({ body: h.body, at: h.at ?? createdAt })),
    { body, at: createdAt },
  ];
  let log = newLog(bodies[0]!.body, createdAt);
  for (const b of bodies.slice(1)) {
    log = addVersion(log, {
      body: b.body,
      source: 'edited',
      by: null,
      at: b.at,
      note: 'Recovered from the edit history',
    });
  }
  return log;
}

function trim(log: VersionLog): VersionLog {
  if (log.versions.length <= MAX_VERSIONS) return log;
  const keep = new Set([1, log.current, log.approved?.n ?? -1]);
  const versions = [...log.versions];
  // Drop the oldest ones that are not the original, current or approved.
  while (versions.length > MAX_VERSIONS) {
    const i = versions.findIndex((v) => !keep.has(v.n));
    if (i < 0) break;
    versions.splice(i, 1);
  }
  return { ...log, versions };
}

/**
 * Add a version (it becomes current). The same content as the current version
 * adds nothing.
 */
export function addVersion(
  log: VersionLog,
  v: {
    body: unknown;
    source: VersionSource;
    by: string | null;
    at?: string;
    basedOn?: number | null;
    note?: string | null;
  },
): VersionLog {
  const hash = bodyFingerprint(v.body);
  const current = log.versions.find((x) => x.n === log.current);
  if (current && current.hash === hash) return log;
  const n = Math.max(...log.versions.map((x) => x.n)) + 1;
  return trim({
    ...log,
    current: n,
    versions: [
      ...log.versions,
      {
        n,
        source: v.source,
        by: v.by,
        at: v.at ?? new Date().toISOString(),
        body: v.body,
        hash,
        ...(v.basedOn ? { basedOn: v.basedOn } : {}),
        ...(v.note ? { note: v.note } : {}),
      },
    ],
  });
}

/** Mark the current version as the approved one. */
export function markApproved(
  log: VersionLog,
  by: string | null,
  at = new Date().toISOString(),
): VersionLog {
  return { ...log, approved: { n: log.current, by, at } };
}

export function findVersion(log: VersionLog, n: number): ContentVersion | null {
  return log.versions.find((v) => v.n === n) ?? null;
}

export interface VersionSummary {
  n: number;
  source: VersionSource;
  label: string;
  by: string | null;
  at: string;
  basedOn: number | null;
  note: string | null;
  isOriginal: boolean;
  isCurrent: boolean;
  isApproved: boolean;
}

export function summarizeVersions(log: VersionLog): VersionSummary[] {
  return [...log.versions].reverse().map((v) => ({
    n: v.n,
    source: v.source,
    label: VERSION_SOURCE_LABEL[v.source],
    by: v.by,
    at: v.at,
    basedOn: v.basedOn ?? null,
    note: v.note ?? null,
    isOriginal: v.n === 1,
    isCurrent: v.n === log.current,
    isApproved: v.n === log.approved?.n,
  }));
}
